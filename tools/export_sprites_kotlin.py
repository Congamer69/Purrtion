"""Exports the pixel sprites of the iOS app (Shared/PixelSprites.swift) to Kotlin for the Android app,
so both platforms always draw the same cats.

Usage: python3 tools/export_sprites_kotlin.py
Writes android/app/src/main/java/de/purrtion/app/ui/pixel/Sprites.kt
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "Shared", "PixelSprites.swift")
DST = os.path.join(ROOT, "android", "app", "src", "main", "java", "de", "purrtion", "app", "ui", "pixel", "Sprites.kt")


def ears_fn(extra):
    rows = env["ears"]
    out = []
    for i, row in enumerate(rows):
        out.append(row if i >= len(extra) else row[:13] + extra[i])
    return out


def main():
    global env
    text = open(SRC, encoding="utf-8").read()
    # Only the part with sprite definitions.
    text = text[text.index("enum Sprites"):]
    # Swift → Python expressions
    text = re.sub(r"Array\((\w+)\.suffix\((\d+)\)\)", r"\1[-\2:]", text)
    text = re.sub(r"\bears\(\[", "ears_fn([", text)
    pattern = re.compile(r"(?:private )?static let (\w+)\s*=\s*", re.M)
    env = {"ears_fn": ears_fn}
    sprites = []
    pos = 0
    while True:
        m = pattern.search(text, pos)
        if not m:
            break
        name = m.group(1)
        start = m.end()
        # expression runs until the matching end: balance brackets/parens
        depth, i, in_str = 0, start, False
        while i < len(text):
            c = text[i]
            if c == '"':
                in_str = not in_str
            elif not in_str:
                if c in "([":
                    depth += 1
                elif c in ")]":
                    depth -= 1
                elif c == "\n" and depth == 0 and text[start:i].strip():
                    break
            i += 1
        expr = text[start:i].strip()
        pos = i
        is_sprite = expr.startswith("PixelSprite(")
        if is_sprite:
            expr = expr[len("PixelSprite("):-1]
        value = eval(expr, env)
        env[name] = value
        if is_sprite:
            sprites.append((name, value))

    lines = [
        "// Generated by tools/export_sprites_kotlin.py from Shared/PixelSprites.swift – do not edit by hand.",
        "package de.purrtion.app.ui.pixel",
        "",
        "object Sprites {",
    ]
    for name, rows in sprites:
        body = ",\n".join(f'        "{r}"' for r in rows)
        lines.append(f"    val {name} = PixelSprite(listOf(\n{body},\n    ))")
    lines.append("}")
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    open(DST, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"{len(sprites)} sprites → {DST}")


if __name__ == "__main__":
    main()
